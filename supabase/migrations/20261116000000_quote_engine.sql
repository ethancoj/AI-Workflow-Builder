-- Placeholder merchant used by the frontend until auth exists (apps/web/src/lib/merchant.ts).
insert into public.merchants (id, name)
values ('00000000-0000-0000-0000-000000000000', 'Demo merchant (placeholder)')
on conflict (id) do nothing;

-- Merchant-defined pricing rubrics. `levels` is the JSON list of
-- {level, name, description, price, visual_cues[]} validated by the API's Rubric model.
create table if not exists public.rubrics (
  id                   uuid primary key default gen_random_uuid(),
  merchant_id          uuid not null references public.merchants (id) on delete cascade,
  name                 text not null,
  service_type         text not null default 'aircon',
  levels               jsonb not null,
  escalation_threshold real not null default 0.6,
  created_at           timestamptz not null default now()
);
create index if not exists rubrics_merchant_id_idx on public.rubrics (merchant_id);

-- One row per VLM photo assessment. `id` is generated by the API so the photo
-- can be uploaded under the same id before the row is inserted.
create table if not exists public.quote_assessments (
  id               uuid primary key,
  merchant_id      uuid not null references public.merchants (id) on delete cascade,
  rubric_id        uuid references public.rubrics (id) on delete set null, -- null for unsaved demo rubrics
  image_path       text,  -- object path inside the private quote-images bucket
  condition_level  integer not null,
  level_name       text not null,
  price_estimate   numeric(10, 2) not null,
  confidence       real not null,
  reasoning        text,
  key_observations jsonb not null default '[]'::jsonb,
  escalated        boolean not null,
  created_at       timestamptz not null default now()
);
create index if not exists quote_assessments_merchant_created_idx
  on public.quote_assessments (merchant_id, created_at desc);

-- RLS on with no policies: only the backend's service key can access these tables.
-- The browser (anon key) is denied.
alter table public.rubrics enable row level security;
alter table public.quote_assessments enable row level security;

-- Private bucket for customer photos (NFR4). Objects are only reachable with the
-- service key or a signed URL, so there are no public links.
insert into storage.buckets (id, name, public)
values ('quote-images', 'quote-images', false)
on conflict (id) do update set public = false;

-- Make the REST API see the new tables immediately.
notify pgrst, 'reload schema';
